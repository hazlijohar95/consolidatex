import Foundation

/// The shell functions that route `claude`, `codex` and `opencode` through `acc launch`,
/// so every new session starts on the tool's current account.
public enum ShellInit {
    public enum Shell: String, CaseIterable, Sendable {
        case zsh, bash, fish

        /// The file the hook line goes in, and the line itself.
        public func hook(home: String = userHome()) -> (file: String, line: String) {
            switch self {
            case .zsh: (home + "/.zshrc", #"eval "$(acc shell-init zsh)""#)
            case .bash: (Self.bashLoginFile(home: home), #"eval "$(acc shell-init bash)""#)
            case .fish: (home + "/.config/fish/conf.d/acc.fish", "acc shell-init fish | source")
            }
        }

        /// Terminal on macOS starts bash as a login shell, which skips .bashrc and reads only the
        /// first of these that exists, so creating .bash_profile would hide an existing .profile.
        static func bashLoginFile(home: String) -> String {
            let candidates = [".bash_profile", ".bash_login", ".profile"].map { home + "/" + $0 }
            return candidates.first(where: FileManager.default.fileExists) ?? candidates[0]
        }

        public static func from(path: String?) -> Shell? {
            path.flatMap { Shell(rawValue: URL(fileURLWithPath: $0).lastPathComponent) }
        }
    }

    public static let marker = "# acc: start AI coding tools on the account you picked (Consolidatex)"

    public static func script(for shell: Shell) -> String {
        let commands = Tool.allCases.map(\.spec.command)
        switch shell {
        case .zsh, .bash:
            return (["# Generated by `acc shell-init \(shell.rawValue)`."]
                + commands.map { "\($0)() { command acc launch \($0) -- \"$@\"; }" }).joined(separator: "\n") + "\n"
        case .fish:
            return (["# Generated by `acc shell-init fish`."]
                + commands.map { "function \($0) --wraps \($0)\n    command acc launch \($0) -- $argv\nend" }).joined(separator: "\n") + "\n"
        }
    }

    /// Earlier versions put bash's hook in .bashrc; one there still counts, rather than adding a second.
    public static func isInstalled(_ shell: Shell, home: String = userHome()) -> Bool {
        let (file, line) = shell.hook(home: home)
        let files = shell == .bash ? [file, home + "/.bashrc"] : [file]
        return files.contains { ((try? String(contentsOfFile: $0, encoding: .utf8)) ?? "").contains(line) }
    }

    public enum HookResult: Equatable, Sendable { case alreadyInstalled, installed, replacedLegacy }

    /// Adds the hook line to the shell's startup file, once. Replaces the line older acc
    /// versions used (`source ~/.config/acc/acc.zsh`).
    @discardableResult
    public static func installHook(_ shell: Shell, home: String = userHome()) throws -> HookResult {
        if isInstalled(shell, home: home) { return .alreadyInstalled }
        let (file, line) = shell.hook(home: home)
        let existing = (try? String(contentsOfFile: file, encoding: .utf8)) ?? ""
        var lines = existing.components(separatedBy: "\n")
        if let legacy = lines.firstIndex(where: { $0.contains(".config/acc/acc.zsh") }) {
            lines[legacy] = line
            try write(lines.joined(separator: "\n"), to: file)
            // The old wrapper only knew `claude`; nothing sources it any more.
            try? FileManager.default.removeItem(atPath: home + "/.config/acc/acc.zsh")
            return .replacedLegacy
        }
        let prefix = existing.isEmpty || existing.hasSuffix("\n") ? existing : existing + "\n"
        try write(prefix + "\n\(marker)\n\(line)\n", to: file)
        return .installed
    }

    private static func write(_ text: String, to file: String) throws {
        try FileManager.default.createDirectory(atPath: (file as NSString).deletingLastPathComponent, withIntermediateDirectories: true)
        try text.write(toFile: file, atomically: true, encoding: .utf8)
    }
}

/// Finds accounts a person already has before acc knew about them.
public enum Discovery {
    public struct Candidate: Equatable, Sendable {
        public let tool: Tool
        public let label: String
        /// nil = the tool's default folder.
        public let configDir: String?
    }

    public static func find(home: String = userHome(), excluding registry: Registry = .empty) -> [Candidate] {
        let fm = FileManager.default
        let t3 = t3ClaudeLabels(home: home)
        /// `named` is the T3 Code name, if any; `folder` the fallback.
        var found: [(tool: Tool, configDir: String?, named: String?, folder: String)] = []
        let names = ((try? fm.contentsOfDirectory(atPath: home)) ?? []).sorted()

        for tool in Tool.allCases {
            let spec = tool.spec
            let marker: String = switch tool {
            case .claude: home + "/.claude.json"
            case .codex: home + "/.codex"
            case .opencode: home + "/.local/share/opencode"
            }
            if fm.fileExists(atPath: marker) {
                found.append((tool, nil, tool == .claude ? t3[""] : nil, "\(spec.name) (default)"))
            }
            // Sibling folders such as ~/.claude-work or ~/.codex-personal.
            let prefix = String(spec.newAccountPrefix.dropFirst())  // without the leading "."
            for name in names where name.hasPrefix("." + prefix) {
                let dir = home + "/" + name
                guard isAccountFolder(dir, tool: tool) else { continue }
                let named = tool == .claude ? t3[canonical(dir)] : nil
                found.append((tool, "~/" + name, named, String(name.dropFirst(prefix.count + 1))))
            }
        }
        // Named for who is logged in, so "acc2" reads as "hazli"; two logins with one email get their plan added.
        var taken = Set(registry.accounts.map { $0.label.lowercased() })
        return found.filter { !registry.knows($0.tool, configDir: $0.configDir, home: home) }.map { f in
            let identity = Identity.read(Account(id: "", tool: f.tool, label: "", configDir: f.configDir), home: home)
            let person = identity?.email?.split(separator: "@").first.map(String.init)
            let options = [f.named, person, person.flatMap { p in identity?.plan.map { "\(p) · \($0)" } }, f.folder]
            let label = options.compactMap { $0 }.first { !taken.contains($0.lowercased()) } ?? f.folder
            taken.insert(label.lowercased())
            return Candidate(tool: f.tool, label: label, configDir: f.configDir)
        }
    }

    static func isAccountFolder(_ dir: String, tool: Tool) -> Bool {
        let fm = FileManager.default
        switch tool {
        case .claude: return fm.fileExists(atPath: dir + "/.claude.json")
        case .codex: return fm.fileExists(atPath: dir + "/auth.json") || fm.fileExists(atPath: dir + "/config.toml")
        case .opencode: return fm.fileExists(atPath: dir + "/opencode")
        }
    }

    /// T3 Code names its Claude providers; reuse those names. Keyed by canonical folder, "" for the default.
    static func t3ClaudeLabels(home: String) -> [String: String] {
        guard let data = FileManager.default.contents(atPath: home + "/.t3/userdata/settings.json"),
              let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let instances = root["providerInstances"] as? [String: [String: Any]]
        else { return [:] }
        var labels: [String: String] = [:]
        for instance in instances.values where instance["driver"] as? String == "claudeAgent" && instance["enabled"] as? Bool != false {
            guard let name = instance["displayName"] as? String else { continue }
            let path = (instance["config"] as? [String: Any])?["homePath"] as? String
            let key = path.map { canonical($0.hasPrefix("~/") ? home + $0.dropFirst(1) : $0) } ?? ""
            labels[key] = name
        }
        return labels
    }
}

/// Points Claude Code's status line at `acc statusline` by editing settings.json in place,
/// keeping its formatting. Leaves an existing, different status line alone.
public enum StatusLineSetup {
    public enum Result: Equatable, Sendable { case alreadyInstalled, installed, otherStatusLine(String) }

    /// For every Claude Code account sharing `primary`'s settings, run by the `acc` at `acc`.
    public static func install(for primary: Account, acc: String, home: String = userHome()) throws -> Result {
        try install(settings: primary.folder(home: home) + "/settings.json", command: acc + " statusline")
    }

    public static func install(settings path: String, command: String) throws -> Result {
        let text = (try? String(contentsOfFile: path, encoding: .utf8)) ?? "{}\n"
        let root = (try? JSONSerialization.jsonObject(with: Data(text.utf8))) as? [String: Any] ?? [:]
        if let existing = (root["statusLine"] as? [String: Any])?["command"] as? String {
            return existing.contains("acc statusline") ? .alreadyInstalled : .otherStatusLine(existing)
        }
        guard let brace = text.firstIndex(of: "{") else { throw AccError.system("\(path) is not a JSON object") }
        let entry = #"  "statusLine": { "type": "command", "command": "\#(command)" }"#
        let rest = text[text.index(after: brace)...]
        let isEmpty = rest.trimmingCharacters(in: .whitespacesAndNewlines) == "}"
        let updated = String(text[...brace]) + "\n" + entry + (isEmpty ? "\n" : ",") + (isEmpty ? "}\n" : String(rest))
        guard (try? JSONSerialization.jsonObject(with: Data(updated.utf8))) != nil else {
            throw AccError.system("could not add the status line to \(path) safely; add it by hand")
        }
        try updated.write(toFile: path, atomically: false, encoding: .utf8)
        return .installed
    }
}
